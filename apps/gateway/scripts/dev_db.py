"""
Local DEV database for running the gateway on your PC (e.g. to test the app on a phone)
when Docker is not installed. NOT the team database: the team standard is
`docker compose up -d` (Postgres + pgvector + Redis from data-layer).

It creates a private PostgreSQL cluster with the locally installed PostgreSQL programs in
apps/gateway/.devdb/ (gitignored), on 127.0.0.1:55432, applies the team's 01_schema.sql
(minus pgvector), runs the gateway migrations and seeds the 4 modules. It writes
apps/gateway/.devdb/gateway.env with a generated DB password and JWT secret (local only).

Usage (from apps/gateway, with the venv active):
    python -m scripts.dev_db start     # create on first run, otherwise just start
    python -m scripts.dev_db status
    python -m scripts.dev_db stop
    python -m scripts.dev_db reset --yes   # stop and delete ALL local dev data

Then run the gateway against it:
    $env:GATEWAY_ENV_FILE = ".devdb\\gateway.env"
    python -m uvicorn app.main:app --host 0.0.0.0 --port 8000
"""

import argparse
import asyncio
import os
import secrets
import shutil
import sys
from pathlib import Path

from scripts import local_pg

DEVDB_DIR = local_pg.GATEWAY_DIR / ".devdb"
DATA_DIR = DEVDB_DIR / "data"
ENV_FILE = DEVDB_DIR / "gateway.env"
LOG_FILE = DEVDB_DIR / "postgres.log"
DB_NAME = "eduarai"
DEFAULT_PORT = 55432


def _read_env() -> dict:
    values = {}
    if ENV_FILE.is_file():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip()
    return values


def _write_env(port: int, password: str, jwt_secret: str) -> None:
    ENV_FILE.write_text(
        "# Generated by scripts/dev_db.py for the LOCAL dev database only. Never commit.\n"
        "DATABASE_HOST=127.0.0.1\n"
        f"DATABASE_PORT={port}\n"
        "POSTGRES_USER=postgres\n"
        f"DB_PASSWORD={password}\n"
        f"POSTGRES_DB={DB_NAME}\n"
        f"JWT_SECRET={jwt_secret}\n"
        "GATEWAY_HOST=0.0.0.0\n"
        "GATEWAY_PORT=8000\n",
        encoding="utf-8",
    )


async def _prepare_database(port: int, password: str) -> None:
    await local_pg.create_database("127.0.0.1", port, password, DB_NAME, with_schema=True, replace=False)
    # Migrations + seed through the normal setup script, pointed at the dev database
    os.environ["GATEWAY_ENV_FILE"] = str(ENV_FILE)
    from app.config import get_settings
    get_settings.cache_clear()
    from scripts import setup_db
    report = await setup_db.run(seed=True, database_url=local_pg.database_url("127.0.0.1", port, password, DB_NAME))
    print(f"  migrations: {', '.join(report.migrations_applied)}")
    print(f"  modules   : {report.modules_created} created, {report.modules_skipped} already present")
    print(f"  test user : {report.user_status}")


def start() -> int:
    pg_bin = local_pg.find_pg_bin()
    env = _read_env()

    if not DATA_DIR.exists():
        port = int(os.getenv("DEV_DB_PORT", DEFAULT_PORT))
        password = secrets.token_urlsafe(24)
        print(f"Creating local dev database in {DEVDB_DIR} ...")
        local_pg.init_cluster(pg_bin, DATA_DIR, password)
        _write_env(port, password, secrets.token_urlsafe(48))
        env = _read_env()
    port, password = int(env["DATABASE_PORT"]), env["DB_PASSWORD"]

    if local_pg.cluster_running(pg_bin, DATA_DIR):
        print(f"Local dev database already running on 127.0.0.1:{port}")
    else:
        local_pg.start_cluster(pg_bin, DATA_DIR, port, LOG_FILE)
        print(f"Local dev database started on 127.0.0.1:{port}")

    asyncio.run(_prepare_database(port, password))
    print("\n[OK] Ready. Start the gateway with:")
    print('  $env:GATEWAY_ENV_FILE = ".devdb\\gateway.env"')
    print("  python -m uvicorn app.main:app --host 0.0.0.0 --port 8000")
    print("\nTip: set SEED_USER_PASSWORD before 'start' to also create the demo_student account.")
    return 0


def stop() -> int:
    if not DATA_DIR.exists():
        print("No local dev database exists.")
        return 0
    pg_bin = local_pg.find_pg_bin()
    local_pg.stop_cluster(pg_bin, DATA_DIR)
    print("Local dev database stopped.")
    return 0


def status() -> int:
    if not DATA_DIR.exists():
        print("No local dev database. Create it with: python -m scripts.dev_db start")
        return 1
    running = local_pg.cluster_running(local_pg.find_pg_bin(), DATA_DIR)
    port = _read_env().get("DATABASE_PORT", "?")
    print(f"Local dev database: {'running' if running else 'stopped'} (127.0.0.1:{port}, data in {DATA_DIR})")
    return 0 if running else 1


def reset(confirmed: bool) -> int:
    if not confirmed:
        print("This deletes ALL local dev data in .devdb. Re-run with --yes to confirm.")
        return 1
    if DATA_DIR.exists():
        local_pg.stop_cluster(local_pg.find_pg_bin(), DATA_DIR)
    shutil.rmtree(DEVDB_DIR, ignore_errors=True)
    print("Local dev database deleted.")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Manage the gateway's LOCAL dev PostgreSQL (not the team database).")
    parser.add_argument("command", choices=["start", "stop", "status", "reset"])
    parser.add_argument("--yes", action="store_true", help="confirm 'reset'")
    args = parser.parse_args(argv)
    try:
        if args.command == "start":
            return start()
        if args.command == "stop":
            return stop()
        if args.command == "status":
            return status()
        return reset(args.yes)
    except (local_pg.PostgresNotFound, FileNotFoundError) as e:
        print(f"[ERROR] {e}")
        return 2


if __name__ == "__main__":
    sys.exit(main())
